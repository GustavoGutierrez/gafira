#!/usr/bin/env bash
# Local skill registry: refresh | resolve NAME... | add DIR
# Writes <project>/.atl/skill-registry.md (gitignored). Needs only coreutils, awk, sed, find.
set -euo pipefail

root=${SKILL_REGISTRY_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)}
home=${HOME:?HOME must be set}
reg=${SKILL_REGISTRY_OUT:-$root/.atl/skill-registry.md}
extra=$(dirname "$reg")/extra-sources

# Source dirs in priority order: project first (wins on duplicate names), then user dirs.
project_src=(".claude/skills" ".agents/skills")
user_src=(".agents/skills" ".config/opencode/skills" ".claude/skills" ".gemini/skills"
  ".gemini/antigravity/skills" ".gemini/antigravity-cli/skills" ".cursor/skills"
  ".copilot/skills" ".codex/skills" ".qwen/skills" ".kiro/skills" ".hermes/skills")

# Print "name<TAB>description" from a SKILL.md front matter (plain, quoted, or folded > / |).
front() {
  awk '
    NR == 1 && $0 != "---" { exit }
    NR > 1 && $0 == "---" { exit }
    /^name:/ { sub(/^name:[ \t]*/, ""); gsub(/^["\047]|["\047]$/, ""); name = $0; mode = ""; next }
    /^description:/ {
      sub(/^description:[ \t]*/, "")
      if ($0 ~ /^[>|][-+]?[ \t]*$/) { mode = "fold"; desc = ""; next }
      gsub(/^["\047]|["\047]$/, ""); desc = $0; mode = ""; next
    }
    mode == "fold" && /^[ \t]+/ { sub(/^[ \t]+/, ""); desc = (desc == "" ? $0 : desc " " $0); next }
    /^[A-Za-z_-]+:/ { mode = "" }
    END { gsub(/\|/, "\\|", desc); if (name != "") printf "%s\t%s\n", name, desc }
  ' "$1"
}

refresh() {
  local tmp rows list d s f line n
  tmp=$(mktemp); rows=$(mktemp); list=$(mktemp)
  trap 'rm -f "$tmp" "$rows" "$list"' RETURN
  for d in "${project_src[@]}"; do echo "project	$root/$d	$d" >>"$list"; done
  for d in "${user_src[@]}"; do echo "user	$home/$d	\$HOME/$d" >>"$list"; done
  if [ -f "$extra" ]; then
    while IFS= read -r d; do if [ -n "$d" ]; then echo "user	$d	$d" >>"$list"; fi; done <"$extra"
  fi
  while IFS=$'\t' read -r s d _; do
    [ -d "$d" ] || continue
    # d is a skills root (d/*/SKILL.md) or a single skill dir (d/SKILL.md)
    { find -L "$d" -mindepth 2 -maxdepth 2 -name SKILL.md; if [ -f "$d/SKILL.md" ]; then echo "$d/SKILL.md"; fi; } 2>/dev/null | sort |
      while IFS= read -r f; do
        line=$(front "$f") || continue
        [ -n "$line" ] || continue
        n=${line%%$'\t'*}
        printf '%s\t%s\t%s\t%s\n' "$n" "$s" "${line#*$'\t'}" "$f"
      done >>"$rows"
  done <"$list"
  # first occurrence of a name wins (list order = project before user)
  awk -F'\t' '!seen[$1]++' "$rows" | sort -t$'\t' -k1,1 >"$tmp"
  mkdir -p "$(dirname "$reg")"
  {
    echo "# Skill Registry — $(basename "$root")"
    echo
    echo "<!-- Generated by .agents/skills/skill-registry/refresh.sh. Do not edit; rerun it to regenerate. -->"
    echo
    echo "Last updated: $(date +%F)"
    echo
    echo "## Sources scanned"
    echo
    while IFS=$'\t' read -r _ _ label; do echo "- $label"; done <"$list"
    echo
    echo "## Contract"
    echo
    echo "**Delegator use only.** This registry is an index, not a summary. Agents resolve skill names to exact \`SKILL.md\` paths here (and pass them to any subagent) and read the full file before work."
    echo
    echo "## Skills"
    echo
    echo "| Skill | Trigger / description | Scope | Path |"
    echo "| --- | --- | --- | --- |"
    awk -F'\t' '{ printf "| `%s` | %s | %s | `%s` |\n", $1, $3, $2, $4 }' "$tmp"
    echo
    echo "## Loading protocol"
    echo
    echo "1. Match the task against the \`Trigger / description\` column."
    echo "2. Pass only the matching \`Path\` values to the subagent under \`## Skills to load before work\`."
    echo "3. If a name is not listed, report it as unavailable; never guess a path."
  } >"$reg"
  echo "wrote $reg ($(wc -l <"$tmp") skills)" >&2
}

lookup() { # lookup NAME -> path (empty when absent)
  [ -f "$reg" ] || return 0
  awk -F'|' -v n="$1" '{ k = $2; gsub(/[ `]/, "", k) } k == n { p = $(NF - 1); gsub(/^ *`|` *$/, "", p); print p; exit }' "$reg"
}

case "${1:-refresh}" in
  refresh) refresh ;;
  resolve)
    shift; [ $# -gt 0 ] || { echo "usage: refresh.sh resolve NAME..." >&2; exit 2; }
    [ -f "$reg" ] || refresh
    rc=0; refreshed=0
    for n in "$@"; do
      p=$(lookup "$n")
      if [ -z "$p" ] && [ "$refreshed" = 0 ]; then refresh; refreshed=1; p=$(lookup "$n"); fi
      if [ -n "$p" ]; then printf '%s\t%s\n' "$n" "$p"; else printf '%s\tunavailable\n' "$n"; rc=1; fi
    done
    exit "$rc" ;;
  add)
    [ -n "${2:-}" ] && [ -d "$2" ] || { echo "usage: refresh.sh add DIR (a skills root or one skill dir)" >&2; exit 2; }
    mkdir -p "$(dirname "$extra")"
    d=$(cd "$2" && pwd)
    grep -qxF "$d" "$extra" 2>/dev/null || echo "$d" >>"$extra"
    refresh ;;
  *) echo "usage: refresh.sh [refresh | resolve NAME... | add DIR]" >&2; exit 2 ;;
esac
