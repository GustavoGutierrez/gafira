//! Validates `assets/i18n/{es,en}.toml` and compiles them to sorted static
//! tables (02 §14.5, ADR-09). Stands in for `xtask gen-i18n` until `xtask`
//! exists. The build fails, naming the key, when:
//!
//! - a key is not 2 or 3 `[a-z][a-z0-9_]*` segments (02 §14.2);
//! - a value is neither text nor a table of CLDR plural categories with `other`;
//! - a key exists in one language only, or the two use different `{parameters}`.
//!
//! CLDR's required categories per language are checked by a crate test with
//! `icu_plurals`, which a build script cannot use without building it twice.

use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

const LANGUAGES: [&str; 2] = ["es", "en"];
const CATEGORIES: [&str; 6] = ["zero", "one", "two", "few", "many", "other"];

enum Entry {
    Text(String),
    Plural(BTreeMap<String, String>),
}

impl Entry {
    fn texts(&self) -> Vec<&str> {
        match self {
            Self::Text(t) => vec![t.as_str()],
            Self::Plural(forms) => forms.values().map(String::as_str).collect(),
        }
    }
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dir = manifest.join("../../assets/i18n");
    let mut catalogs = BTreeMap::new();
    for lang in LANGUAGES {
        let path = dir.join(format!("{lang}.toml"));
        println!("cargo:rerun-if-changed={}", path.display());
        catalogs.insert(lang, load(&path).unwrap_or_else(|e| fail(&path, &e)));
    }
    if let Err(e) = compare(&catalogs["es"], &catalogs["en"]) {
        fail(&dir, &e);
    }
    let mut out = String::from("// Generated by build.rs from assets/i18n/*.toml. Do not edit.\n");
    for lang in LANGUAGES {
        render(&mut out, lang, &catalogs[lang]);
    }
    let dest = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("catalogs.rs");
    fs::write(&dest, out).expect("write catalogs.rs");
}

fn fail(path: &Path, message: &str) -> ! {
    panic!("{}: {message}", path.display());
}

fn load(path: &Path) -> Result<BTreeMap<String, Entry>, String> {
    let text = fs::read_to_string(path).map_err(|e| e.to_string())?;
    let table: toml::Table = text.parse().map_err(|e: toml::de::Error| e.to_string())?;
    let mut out = BTreeMap::new();
    flatten("", &table, &mut out)?;
    Ok(out)
}

fn flatten(
    prefix: &str,
    table: &toml::Table,
    out: &mut BTreeMap<String, Entry>,
) -> Result<(), String> {
    for (name, value) in table {
        let key = if prefix.is_empty() {
            name.clone()
        } else {
            format!("{prefix}.{name}")
        };
        match value {
            toml::Value::String(text) => {
                check_key(&key)?;
                out.insert(key, Entry::Text(text.clone()));
            }
            toml::Value::Table(inner) if is_plural(inner) => {
                check_key(&key)?;
                let mut forms = BTreeMap::new();
                for (category, form) in inner {
                    let form = form
                        .as_str()
                        .ok_or_else(|| format!("{key}.{category} is not text"))?;
                    forms.insert(category.clone(), form.to_string());
                }
                out.insert(key, Entry::Plural(forms));
            }
            toml::Value::Table(inner) => flatten(&key, inner, out)?,
            _ => return Err(format!("{key} is neither text, a plural nor a section")),
        }
    }
    Ok(())
}

/// A table whose keys are all CLDR categories is a plural; it must have `other`.
fn is_plural(table: &toml::Table) -> bool {
    !table.is_empty() && table.keys().all(|k| CATEGORIES.contains(&k.as_str()))
}

fn check_key(key: &str) -> Result<(), String> {
    let segments: Vec<&str> = key.split('.').collect();
    let valid_segment = |s: &&str| {
        let mut bytes = s.bytes();
        bytes.next().is_some_and(|b| b.is_ascii_lowercase())
            && bytes.all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
    };
    if (2..=3).contains(&segments.len()) && segments.iter().all(valid_segment) {
        Ok(())
    } else {
        Err(format!("{key} is not a valid message key"))
    }
}

/// The `{name}` parameters of a text.
fn params(text: &str) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    let mut rest = text;
    while let Some(start) = rest.find('{') {
        let after = &rest[start + 1..];
        match after.find('}') {
            Some(end) => {
                out.insert(after[..end].to_string());
                rest = &after[end + 1..];
            }
            None => break,
        }
    }
    out
}

fn entry_params(entry: &Entry) -> BTreeSet<String> {
    entry.texts().into_iter().flat_map(params).collect()
}

fn compare(es: &BTreeMap<String, Entry>, en: &BTreeMap<String, Entry>) -> Result<(), String> {
    for (key, entry) in es {
        if let Entry::Plural(forms) = entry
            && !forms.contains_key("other")
        {
            return Err(format!("{key} is a plural without `other` in es"));
        }
        let other = en
            .get(key)
            .ok_or_else(|| format!("{key} is in es but not in en"))?;
        if entry_params(entry) != entry_params(other) {
            return Err(format!("{key} has different parameters in es and en"));
        }
    }
    for (key, entry) in en {
        if let Entry::Plural(forms) = entry
            && !forms.contains_key("other")
        {
            return Err(format!("{key} is a plural without `other` in en"));
        }
        if !es.contains_key(key) {
            return Err(format!("{key} is in en but not in es"));
        }
    }
    Ok(())
}

fn render(out: &mut String, lang: &str, entries: &BTreeMap<String, Entry>) {
    let name = lang.to_ascii_uppercase();
    let _ = writeln!(out, "pub(crate) static {name}: &[(&str, Entry)] = &[");
    for (key, entry) in entries {
        match entry {
            Entry::Text(text) => {
                let _ = writeln!(out, "    ({key:?}, Entry::Text({text:?})),");
            }
            Entry::Plural(forms) => {
                let form = |c: &str| match forms.get(c) {
                    Some(t) => format!("Some({t:?})"),
                    None => "None".to_string(),
                };
                let _ = writeln!(
                    out,
                    "    ({key:?}, Entry::Plural(Plural {{ zero: {}, one: {}, two: {}, few: {}, many: {}, other: {:?} }})),",
                    form("zero"),
                    form("one"),
                    form("two"),
                    form("few"),
                    form("many"),
                    forms.get("other").map_or("", String::as_str),
                );
            }
        }
    }
    out.push_str("];\n");
}
